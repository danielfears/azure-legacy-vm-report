"""Markdown report (GitHub-flavoured tables)."""

from __future__ import annotations

from typing import List

from .collect import LEVEL_ERROR, LEVEL_INFO, LEVEL_WARNING
from .dates import format_datetime
from .model import TYPE_VMSS
from .report import GenerationSummary, Report, TenantReport
from .textfmt import (
    clean_text,
    format_hourly,
    format_money,
    format_pct,
    markdown_escape,
    plural,
)

_LEVEL_LABELS = {LEVEL_ERROR: "Error", LEVEL_WARNING: "Warning", LEVEL_INFO: "Note"}
_ALIGN_RULE = {"l": ":---", "r": "---:"}


def _table(headers: List[str], rows: List[List[str]], aligns: List[str]) -> List[str]:
    out = ["| " + " | ".join(markdown_escape(header) for header in headers) + " |"]
    out.append("| " + " | ".join(_ALIGN_RULE[a] for a in aligns) + " |")
    for row in rows:
        out.append("| " + " | ".join(markdown_escape(cell) for cell in row) + " |")
    return out


def _gen_cells(label: str, summary: GenerationSummary, cur: str, ok: bool) -> List[str]:
    if not ok:
        return [label, summary.generation] + ["n/a"] * 7
    return [
        label,
        summary.generation,
        str(summary.instance_count),
        str(summary.total_vcpus),
        format_money(summary.current_monthly, cur),
        format_money(summary.feb_monthly, cur),
        format_money(summary.monthly_delta, cur, signed=True),
        format_money(summary.annual_delta, cur, signed=True),
        format_pct(summary.effective_hike_pct, signed=True),
    ]


def render_markdown(report: Report) -> str:
    tz = report.tz
    cur = report.currency
    lines: List[str] = []
    if report.demo:
        lines += ["> **Demo data:** synthetic and generated locally. Nothing was read from Azure.", ""]

    lines += [
        "# Azure legacy VM SKU (v1, v2, v3) cost & February 2027 hike report",
        "",
        f"- **Generated:** {format_datetime(report.generated_at, tz)} ({markdown_escape(report.tz_name)})",
        f"- **Hike model:** {markdown_escape(report.policy.label)}",
        f"- **Cost basis:** {markdown_escape(report.cost_basis_description)}",
        f"- **Tenants:** {len(report.tenants)}",
    ]
    lines += [f"- **Note:** {markdown_escape(note)}" for note in report.notes]
    lines += ["", "## Summary by generation", ""]

    headers = [
        "Tenant",
        "Generation",
        "Instances",
        "vCPUs",
        "Current / mo",
        "Feb 2027 / mo",
        "Increase / mo",
        "Increase / yr",
        "Hike %",
    ]
    rows: List[List[str]] = []
    for tenant in report.tenants:
        ok = tenant.fetched
        for gen in report.generations:
            rows.append(_gen_cells(tenant.display_name, tenant.by_generation[gen], cur, ok))
        rows.append(_gen_cells(tenant.display_name, tenant.total_summary, cur, ok))

    if len(report.tenants) > 1:
        any_ok = any(t.fetched for t in report.tenants)
        by_gen = report.totals_by_generation()
        for gen in report.generations:
            rows.append(_gen_cells("All tenants", by_gen[gen], cur, any_ok))
        rows.append(_gen_cells("All tenants", report.grand_total(), cur, any_ok))

    lines += _table(headers, rows, ["l", "l", "r", "r", "r", "r", "r", "r", "r"])

    missing = report.missing_tenants()
    if missing:
        lines += [
            "",
            f"> **Warning:** Totals exclude tenant(s) that could not be read: "
            f"{', '.join(markdown_escape(m) for m in missing)}.",
        ]

    for tenant in report.tenants:
        lines += [""] + _tenant_md(report, tenant)

    lines += ["", f"_Generated by azure-legacy-vm-report {report.version}._", ""]
    return "\n".join(lines)


def _tenant_md(report: Report, tenant: TenantReport) -> List[str]:
    cur = report.currency
    lines = [f"## {markdown_escape(tenant.display_name)}", ""]
    facts = [f"`{clean_text(tenant.tenant_id).replace('`', '')}`"]
    if tenant.default_domain:
        facts.append(markdown_escape(tenant.default_domain))
    if tenant.data.subscription_count is not None:
        facts.append(plural(tenant.data.subscription_count, "subscription") + " visible")
    if tenant.fetched:
        facts.append(f"{tenant.data.total_resources_scanned} compute resource(s) scanned")
        facts.append(f"{len(tenant.records)} legacy (v1-v3) deployment(s)")
    lines.append(" \u00b7 ".join(facts))

    if not tenant.fetched:
        lines += ["", "_VM inventory could not be retrieved for this tenant (see notes)._"]
    elif not tenant.records:
        lines += ["", "_No legacy v1, v2 or v3 VM SKUs are deployed in this tenant._"]
    else:
        lines += ["", "### Legacy SKU breakdown", ""]
        sku_headers = [
            "SKU",
            "Gen",
            "Series",
            "Instances",
            "Running / Dealloc",
            "Current / mo",
            "Feb 2027 / mo",
            "Increase / mo",
            "Increase / yr",
            "Retirement date",
            "Recommended v5 -> v6/v7",
        ]
        sku_rows = [
            [
                row.sku,
                row.generation,
                row.series,
                str(row.instance_count),
                f"{row.running_instances} / {row.deallocated_instances}",
                format_money(row.current_monthly, cur),
                format_money(row.feb_monthly, cur),
                format_money(row.monthly_delta, cur, signed=True),
                format_money(row.annual_delta, cur, signed=True),
                row.retirement_date,
                f"{row.recommended_v5} -> {row.recommended_current}",
            ]
            for row in tenant.sku_rows
        ]
        lines += _table(sku_headers, sku_rows, ["l", "l", "l", "r", "r", "r", "r", "r", "r", "l", "l"])

        lines += ["", "### Subscription breakdown", ""]
        sub_headers = [
            "Subscription",
            "v1",
            "v2",
            "v3",
            "Total instances",
            "vCPUs",
            "Current / mo",
            "Feb 2027 / mo",
            "Increase / mo",
            "Increase / yr",
        ]
        sub_rows = [
            [
                row.subscription_name,
                str(row.v1_instances),
                str(row.v2_instances),
                str(row.v3_instances),
                str(row.total_instances),
                str(row.total_vcpus),
                format_money(row.current_monthly, cur),
                format_money(row.feb_monthly, cur),
                format_money(row.monthly_delta, cur, signed=True),
                format_money(row.annual_delta, cur, signed=True),
            ]
            for row in tenant.subscription_rows
        ]
        lines += _table(sub_headers, sub_rows, ["l", "r", "r", "r", "r", "r", "r", "r", "r", "r"])

        lines += ["", f"### Deployed legacy VMs & scale sets ({len(tenant.records)})", ""]
        vm_headers = [
            "Name",
            "Subscription",
            "Resource group",
            "Region",
            "SKU",
            "Gen",
            "OS / Licensing",
            "State",
            "Schedule",
            "Last mo hrs",
            "Hourly rate",
            "Current / mo",
            "Feb 2027 / mo",
            "Increase / mo",
            "Recommended target",
        ]
        vm_rows = []
        for rec in tenant.records:
            name_label = f"{rec.name} (VMSS x{rec.instance_count})" if rec.resource_type == TYPE_VMSS else rec.name
            os_label = f"{rec.os_type} (AHB)" if rec.hybrid_benefit else rec.os_type
            hrs_label = f"{rec.actual_last_month_hours:.0f}h" if rec.actual_last_month_hours is not None else "n/a"
            vm_rows.append([
                name_label,
                rec.subscription_name,
                rec.resource_group,
                rec.region,
                rec.sku,
                rec.generation,
                os_label,
                rec.power_state,
                rec.auto_shutdown_schedule or "—",
                hrs_label,
                format_hourly(rec.hourly_rate, cur),
                format_money(rec.current_monthly, cur),
                format_money(rec.feb_monthly, cur),
                format_money(rec.monthly_delta, cur, signed=True),
                rec.recommended_v5,
            ])
        lines += _table(vm_headers, vm_rows, ["l", "l", "l", "l", "l", "l", "l", "l", "l", "r", "r", "r", "r", "r", "l"])

    if tenant.issues:
        lines += ["", "### Notes", ""]
        lines += [
            f"- **{_LEVEL_LABELS.get(i.level, 'Note')}** [{markdown_escape(i.feature)}] {markdown_escape(i.message)}"
            for i in tenant.issues
        ]
    return lines
